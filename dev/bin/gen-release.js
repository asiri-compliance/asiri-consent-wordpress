#!/usr/bin/env node
// Writes asiri-consent/includes/release.php from the edge build's manifest and defaults block.
// Usage: node bin/gen-release.js [edge-dir]   (default: ../../packages/consent/dist/edge)

const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const edge = path.resolve(process.argv[2] || path.join(root, '../../packages/consent/dist/edge'))
const manifest = JSON.parse(fs.readFileSync(path.join(edge, 'manifest.json'), 'utf8'))
const defaults = fs.readFileSync(path.join(edge, 'defaults.html'), 'utf8')
const script = manifest.files.find((f) => f.path === 'asiri.js')

if (!script || !/^sha384-[A-Za-z0-9+/=]+$/.test(script.sha384))
  throw new Error('manifest has no valid asiri.js sha384')
if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(manifest.version))
  throw new Error('manifest version is not semver')
if (!/^sha256-[A-Za-z0-9+/=]+$/.test(manifest.defaultsSha256))
  throw new Error('manifest has no defaults hash')

// The manifest's hash is the one a Content-Security-Policy uses: the script's contents, not the tag around it.
const inner = defaults.match(/^<script[^>]*>([\s\S]*)<\/script>\s*$/)
if (!inner) throw new Error('defaults.html is not one script element')
const actual = `sha256-${require('node:crypto').createHash('sha256').update(inner[1]).digest('base64')}`
if (actual !== manifest.defaultsSha256)
  throw new Error('defaults.html does not match the manifest hash')

const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
const out = `<?php
// phpcs:ignoreFile -- generated file.
/**
 * The pinned edge script release. GENERATED by bin/gen-release.js from the edge build's manifest.json.
 * Do not edit by hand: change the build and run bin/build.sh.
 *
 * @package Asiri_Consent
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

define( 'ASIRI_CONSENT_EDGE_VERSION', ${q(manifest.version)} );
define( 'ASIRI_CONSENT_EDGE_INTEGRITY', ${q(script.sha384)} );
define( 'ASIRI_CONSENT_DEFAULTS_SHA256', ${q(manifest.defaultsSha256)} );
define( 'ASIRI_CONSENT_DEFAULTS_HTML', ${q(defaults)} );
`
fs.writeFileSync(path.join(root, 'asiri-consent/includes/release.php'), out)
console.log(`release.php written for edge v${manifest.version}`)
